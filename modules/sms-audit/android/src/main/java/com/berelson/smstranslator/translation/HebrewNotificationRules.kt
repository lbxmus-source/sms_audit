package com.berelson.smstranslator.translation

/** Reusable notification vocabulary. Context comes from the original, never garbled Russian. */
object HebrewNotificationRules {
    fun forText(text: String): List<Pair<String, String>> = buildList {
        addAll(common.filter { it.first != "למספר" || text.contains("להסרה") })
        if (deliveryContext.containsMatchIn(text)) addAll(delivery)
        if (Regex("שיבוץ|גן עירוני|צהרונים|מינהל החינוך").containsMatchIn(text)) {
            addAll(education)
            Regex("(?<![א-ת])ל(תש[א-ת][\"״][א-ת])(?![א-ת])").findAll(text).forEach {
                add(it.value to "на учебный год ${it.groupValues[1]}")
            }
        }
        if (Regex("עמדתך|עמדתכם|מה דעתך|(?:^|[0-9]\\.[ \\t]*)(?:לא )?מוקיר את פועלו").containsMatchIn(text)) addAll(survey)
        if (Regex("מיכלי המשקה|מכלי המשקה|שקים|נהג של חברת").containsMatchIn(text)) addAll(collection)
        if (Regex("כנס|להזמינך|להזמין אתכם|רא[\"״]ל|קבינט").containsMatchIn(text)) addAll(invitation)
        if (Regex("מי התקשר|התקשר אליך|שעון ישראל").containsMatchIn(text)) addAll(telephone)
    }

    /** Only explicit syntactic slots establish unfamiliar names. No word is learned as a brand. */
    fun entities(text: String): List<String> = buildList {
        if (deliveryContext.containsMatchIn(text)) {
            Regex("ביצענו\\s+ספירת\\s+מלאי\\s+בחנות\\s+([^\\r\\n]{2,160}?)\\s+והמשלוח\\s+שמספרו\\s+[A-Z]{1,4}[0-9]{6,18}")
                .findAll(text).forEach { add(it.groupValues[1]) }
            Regex("(?<![א-ת])(?:מחברת|מאת)\\s+([A-Za-z][A-Za-z0-9.-]{1,35}(?:[ \\t]+[A-Za-z][A-Za-z0-9.-]{0,25}){0,3})(?=\\s+(?:צפויה|צפוי|יגיע|תגיע))")
                .findAll(text).forEach { add(it.groupValues[1]) }
            if (text.contains("צ'יטה שליחויות")) add("צ'יטה שליחויות")
        }
        // Courier company and driver's name are bounded by a role and an actual phone number.
        Regex("נהג\\s+של\\s+חברת\\s+([א-תA-Za-z][א-תA-Za-z '\u05f3’-]{1,65}),\\s*(?=0[0-9]{1,2}-?[0-9]{7})")
            .findAll(text).forEach { add(it.groupValues[1].trim()) }
    }.distinct()

