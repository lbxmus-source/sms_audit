object HebrewPhraseRules {
    fun forText(text: String): List<Pair<String, String>> = buildList {
        addAll(common)
        // Advertising elongation is recognised only inside this reviewed expression;
        // never collapse repeated letters in names, identifiers or arbitrary Hebrew words.
        Regex("(?<![א-ת])תשאלו\\s+את\\s+כו{2,}לם(?![א-ת])").findAll(text).forEach {
            add(it.value to "Спросите кого угодно")
        }
        if (Regex("כרטיס|מופע|הופע|אמפי|אולם|קופות").containsMatchIn(text)) addAll(events)
        if (Regex("מסעד|דמי משלוח|עלות משלוח|משלוחה").containsMatchIn(text)) addAll(foodDelivery)
        if (Regex("תושבי|בוחרים|מצביע|מנהיגות|הצטרפ|לישראל|כאן בנט").containsMatchIn(text)) addAll(civic)
        addAll(account)
        if (Regex("הנחה|קופון|מוצרים|לרכישה|קנייה|קונים|רוכשים").findAll(text).count() >= 2) addAll(retail)
    }

